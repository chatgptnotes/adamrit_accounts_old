  v_company_id uuid := '4adfe31a-7073-49fe-bc18-90fd32e00e52';
  v_confirmation text := 'REVIEW_ONLY';
  v_tally_config_ids uuid[];
  v_old_accounts integer := 0;
  v_old_vouchers integer := 0;
  v_inserted_groups integer := 0;
  v_inserted_ledgers integer := 0;
