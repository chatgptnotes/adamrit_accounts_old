  IF v_confirmation <> 'DELETE_DRM_OLD_DATA' THEN
    RAISE EXCEPTION 'Safety stop: review the preflight counts, then set v_confirmation to DELETE_DRM_OLD_DATA';
  END IF;

  SELECT array_agg(id)
    INTO v_tally_config_ids
    FROM public.tally_config
   WHERE lower(company_name) LIKE '%drm%'
      OR lower(company_name) LIKE '%hope%';

  SELECT count(*) INTO v_old_accounts
    FROM public.chart_of_accounts
   WHERE company_id = v_company_id;

  SELECT count(*) INTO v_old_vouchers
    FROM public.vouchers
   WHERE company_id = v_company_id;

  RAISE NOTICE 'Fresh DRM reset: % old chart accounts and % old vouchers will be deleted',
    v_old_accounts, v_old_vouchers;

  UPDATE public.tally_config
     SET is_active = false,
         auto_sync_enabled = false
   WHERE id = ANY(COALESCE(v_tally_config_ids, ARRAY[]::uuid[]));

  DELETE FROM public.approval_queue
   WHERE company_id = v_company_id;

  UPDATE public.payment_obligations
     SET tally_ledger_id = NULL,
         chart_of_accounts_id = NULL
   WHERE tally_ledger_id IN (
     SELECT id FROM public.tally_ledgers
      WHERE company_id = ANY(COALESCE(v_tally_config_ids, ARRAY[]::uuid[]))
   )
      OR chart_of_accounts_id IN (
     SELECT id FROM public.chart_of_accounts
      WHERE company_id = v_company_id
   );

